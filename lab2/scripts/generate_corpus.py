def incident_pages(rng: random.Random, n_pages: int = 45) -> list[str]:
    pages = []
    for page in range(1, n_pages + 1):
        parts = []
        if page == 1:
            parts.append("# Разборы инцидентов поисковой платформы, 2026\n\nКаждая страница — один разбор (сгенерировано детерминированно).")
        if page == INCIDENT_FACT["page"]:
            parts.append(f"## INC-2026-{page:03d}")
            parts.append(INCIDENT_FACT["text"])
            parts.append("Вывод разбора: утверждение «кэш результатов всегда снижает p95» не подтвердилось — "
                         "при большом кэше паузы сборки мусора увеличили хвост задержки.")
        else:
            sym = rng.choice(SYMPTOMS).format(x=rng.choice([350, 600, 900, 1500]), y=rng.choice([2, 5, 8, 12]),
                                              z=rng.choice([2, 4, 6, 12]), n=rng.choice(["search-3", "search-7", "es-data-2"]))
            ci = rng.randrange(len(CAUSES))
            parts.append(f"## INC-2026-{page:03d}")
            parts.append(f"Дата: {rng.randint(1, 28):02d}.{rng.randint(1, 11):02d}.2026. Команда: «{rng.choice(TEAMS)}». "
                         f"Длительность: {rng.choice([7, 12, 25, 40, 75, 120])} мин.")
            parts.append(f"Симптом: {sym}. Причина: {CAUSES[ci]}. Исправление: {FIXES[ci]}.")
            parts.append(f"Урок: {rng.choice(['изменения конфигурации проверяются на копии индекса', 'алерт должен срабатывать на устойчивое нарушение', 'деградация должна включаться автоматически с журналом', 'параметры ранжирования нельзя менять без офлайн-оценки'])}.")
            parts.append(f"Действия: владелец — {rng.choice(TEAMS)}, срок — {rng.randint(1, 4)} недели, статус — {rng.choice(['выполнено', 'в работе', 'запланировано'])}.")
            h = rng.randint(0, 20)
            parts.append(f"Хронология: {h:02d}:{rng.randint(0, 59):02d} — сработал алерт; {h:02d}:{rng.randint(0, 59):02d} — дежурный "
                         f"подтвердил проблему; {h + 1:02d}:{rng.randint(0, 59):02d} — применено исправление; "
                         f"{h + 2:02d}:{rng.randint(0, 59):02d} — метрики вернулись к норме. Пострадало около "
                         f"{rng.choice([2, 5, 10, 25])}% запросов, данные не потеряны.")
        pages.append("\n\n".join(parts))
    return pages


def render(pages: list[str]) -> str:
    return "\n\n".join(f"{PAGE_MARK.format(n=i)}\n\n{body}" for i, body in enumerate(pages, 1)) + "\n"


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    rng = random.Random(SEED)
    docs = {
        "search_engineering_handbook.md": ("Справочник по инженерии поисковых систем", handbook_pages(rng)),
        "ir_course_lectures.md": ("Конспект курса «Информационный поиск»", lecture_pages(rng)),
        "search_incident_reports.md": ("Разборы инцидентов поисковой платформы, 2026", incident_pages(rng)),
    }
    manifest = {"generator": "scripts/generate_corpus.py", "seed": SEED, "page_marker": PAGE_MARK,
                "documents": [], "control_facts": [], "injection": {}}
    for name, (title, pages) in docs.items():
        text = render(pages)
        data = text.encode("utf-8")
        (OUT / name).write_bytes(data)
        manifest["documents"].append({
            "file": name, "title": title, "pages": len(pages), "chars": len(text), "bytes": len(data),
            "lines": len(text.splitlines()), "sha256": hashlib.sha256(data).hexdigest(),
            "min_page_chars": min(len(p) for p in pages), "avg_page_chars": round(sum(len(p) for p in pages) / len(pages))})
    for fid, f in CONTROL.items():
        pos = "beginning" if f["page"] < 50 else ("middle" if f["page"] < 400 else "end")
        manifest["control_facts"].append({"id": fid, "file": "search_engineering_handbook.md", "page": f["page"],
                                          "position": pos, "text": f["text"], "keywords": f["keywords"]})
    manifest["control_facts"].append({"id": LECTURE_FACT["id"], "file": "ir_course_lectures.md", "page": LECTURE_FACT["page"],
                                      "position": "middle", "text": LECTURE_FACT["text"], "keywords": LECTURE_FACT["keywords"]})
    manifest["control_facts"].append({"id": INCIDENT_FACT["id"], "file": "search_incident_reports.md", "page": INCIDENT_FACT["page"],
                                      "position": "beginning", "text": INCIDENT_FACT["text"], "keywords": INCIDENT_FACT["keywords"]})
    manifest["injection"] = {"file": "search_engineering_handbook.md", "page": INJECTION_PAGE, "text": INJECTION}
    (OUT / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    for d in manifest["documents"]:
        print(f"{d['file']}: {d['pages']} pages, {d['chars']} chars, {d['bytes']} bytes, avg page {d['avg_page_chars']} chars")


if __name__ == "__main__":
    main()
