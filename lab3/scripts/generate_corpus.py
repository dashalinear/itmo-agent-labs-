def doc_md(title: str, sections, topic: str, rng: random.Random, extra_pool: int = 2) -> str:
    lines = [f"# {title}", "", rng.choice(POOL[topic]), ""]
    for heading, paras in sections:
        lines += [f"## {heading}", ""]
        for p in paras:
            lines += [p, ""]
        for p in rng.sample(POOL[topic], extra_pool):
            lines += [p, ""]
    return "\n".join(lines).rstrip() + "\n"


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode("utf-8"))


